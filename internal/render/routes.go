// Kernel routing constants shared by the route driver and the FRR config:
// routes live in their own table, tagged with a protocol number nothing
// else on the host uses, and FRR imports that table for redistribution.
// The table must differ from TProxyRouteTbl: that one holds the "local
// default dev lo" route TPROXY needs, and a more specific unicast route in
// the same table would steal marked packets from the local socket.
const (
	RouteTable    = 200
	RouteProtocol = 200
	FRRDistance   = 20
)

// InterfaceAddr is the function the renderer uses to learn the service
// interface's IPv4 address and prefix; overridable in tests.
type InterfaceAddr func(iface string) (netip.Prefix, error)

// SystemInterfaceAddr reads the first IPv4 address of iface.
func SystemInterfaceAddr(iface string) (netip.Prefix, error) {
	ifi, err := net.InterfaceByName(iface)
	if err != nil {
		return netip.Prefix{}, err
	}
	addrs, err := ifi.Addrs()
	if err != nil {
		return netip.Prefix{}, err
	}
	for _, a := range addrs {
		if ipn, ok := a.(*net.IPNet); ok {
			if ip4 := ipn.IP.To4(); ip4 != nil {
				ones, _ := ipn.Mask.Size()
				addr, _ := netip.AddrFromSlice(ip4)
				return netip.PrefixFrom(addr, ones), nil
			}
		}
	}
	return netip.Prefix{}, fmt.Errorf("interface %s has no IPv4 address", iface)
}

func renderRoutes(snap *desired.Snapshot, d Deps, a *Artifacts) error {
	res := routes.Compute(snap, routes.Sources{GeoIP: d.GeoIP, GeoSite: d.GeoSite})
	a.Routes = res.Publish
	a.RouteRejected = res.Rejected
	a.ResolveDomains = res.Domains
	a.Warnings = append(a.Warnings, res.Warnings...)

	if snap.Network.Mode == model.ModeA {
		a.FRR = nil
		return nil
	}
	iface := snap.Network.ServiceIface
	if iface == "" && d.DefaultIface != nil {
		// Not configured (1.x had no such setting): the interface with the
		// default route is the LAN-facing one on a single-homed gateway.
		if di, err := d.DefaultIface(); err == nil && di != "" {
			iface = di
			a.warn("service interface not set; using %s (default route) for OSPF, set it under 网络与模式 to silence this", di)
		}
	}
	var lan netip.Prefix
	if iface != "" && d.IfaceAddr != nil {
		p, err := d.IfaceAddr(iface)
		if err != nil {
			a.warn("service interface %s: %v; OSPF will not join any network until fixed", iface, err)
		} else {
			lan = p
		}
	} else if iface == "" {
		a.warn("service interface not set; OSPF will not join any network")
	}
	a.FRR = []byte(renderFRR(lan, iface))
	return nil
}

// renderFRR produces the integrated frr.conf. It is static apart from the
// router id and LAN network: routes come from kernel table RouteTable via
// "ip import-table", so the file never changes as rules change.
func renderFRR(lan netip.Prefix, iface string) string {
	var b strings.Builder
	b.WriteString("! Generated by EdgeRouteGW. Do not edit: routes are injected into kernel table ")
	fmt.Fprintf(&b, "%d and imported below.\n", RouteTable)
	b.WriteString("frr defaults traditional\nhostname edgeroutegw\nlog syslog informational\nno ipv6 forwarding\n!\n")
	fmt.Fprintf(&b, "ip import-table %d distance %d\n!\n", RouteTable, FRRDistance)
	b.WriteString("router ospf\n")
	if lan.IsValid() {
		fmt.Fprintf(&b, " ospf router-id %s\n", lan.Addr())
		fmt.Fprintf(&b, " network %s area 0\n", lan.Masked())
	}
	fmt.Fprintf(&b, " redistribute table %d\n", RouteTable)
	b.WriteString(" passive-interface default\n")
	if iface != "" {
		fmt.Fprintf(&b, " no passive-interface %s\n", iface)
	}
	b.WriteString("!\nline vty\n!\n")
	return b.String()
}

// RouteSet renders the prefixes as sorted strings (for diffs and tests).
func RouteSet(rs []routes.Route) []string {
	out := make([]string, 0, len(rs))
	for _, r := range rs {
		out = append(out, r.Prefix.String())
	}
	sort.Strings(out)
	return out
}
